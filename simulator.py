#!/bin/env python

import numpy
import itertools
import fractions
import scipy.signal


class Synthesizer:
    def __init__(self, sample_rate=44100, batch_size=4096, output_gain=0.25):
        self._sample_rate = sample_rate
        self._batch_size = batch_size
        self._output_gain = output_gain

        # Frequencies of tones used for mixing.
        # Indices are spaced by halftones
        a4 = 440
        # C5 is 3 halftones above A4,
        # The keyboard starts at C3 (-21), ends at B4 (+2)
        # The mixing frequencies start at C2 (-33), end at B5 (+14)
        self._frequencies = numpy.array([a4 * 2 ** (x / 12) for x in range(-33, +15)])

        # Indices of keys available
        self._key_indices = numpy.arange(12, 36)

        self._busbar_offsets = [-12, 0, 7, 12]  # 16', 8', 5 1/3', 4' on Hammon organ

        # Checking that all frequencies are used and none are missing.
        assert min(self._key_indices) + min(self._busbar_offsets) == 0
        assert max(self._key_indices) + max(self._busbar_offsets) == len(self._frequencies) - 1

        self._mixing = numpy.array([0.5, 1.0, 0.3, 0.6])

        # Indices into self._key_indices, changed from other threads while running
        self._pressed_keys = set()

    @property
    def sample_rate(self):
        return self._sample_rate

    @property
    def batch_size(self):
        return self._batch_size

    @property
    def key_names(self):
        """Note names of the keys, e.g. "C#3"."""
        names = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]
        # Tone index 0 is C2
        return [f"{names[i % 12]}{2 + i // 12}" for i in self._key_indices]

    @property
    def busbar_names(self):
        """Hammond style footages of the busbars, e.g. "5 1/3'"."""
        result = []
        for offset in self._busbar_offsets:
            footage = fractions.Fraction(8 / 2 ** (offset / 12)).limit_denominator(5)
            whole, rest = divmod(footage, 1)
            result.append(f"{whole} {rest}'" if rest else f"{whole}'")
        return result

    def press(self, key):
        if not 0 <= key < len(self._key_indices):
            raise ValueError(f"Key {key} out of range")
        self._pressed_keys.add(key)

    def release(self, key):
        self._pressed_keys.discard(key)

    def release_all(self):
        self._pressed_keys.clear()

    def _square_waves(self):
        """Simulates the square waves generated by the top octave generator
        and the counters/dividers.

        Yields blocks of shape (len(self.frequencies), self.batch_size) with booleans."""

        # Phase accumulator, phases are in cycles, kept in [0, 1)
        steps = (self._frequencies / self._sample_rate)[:, numpy.newaxis]
        # Phase advance from the batch start, for each sample in the batch
        batch_advance = numpy.arange(self._batch_size)[numpy.newaxis] * steps
        batch_step = self._batch_size * steps
        phases = numpy.zeros_like(steps)

        while True:
            block = ((phases + batch_advance) % 1.0) < 0.5
            phases = (phases + batch_step) % 1.0

            yield block

    def _filtered_tones(self):
        """Simulates the filtered tones before mixing.

        Yields blocks of shape (len(self.frequencies), self.batch_size)."""

        # Unity gain Sallen-Key low pass per tone, with R1 = R2 = R,
        # which gives Q = sqrt(C1 / C2) / 2 (~1.58 here) and f0 = 1 / (2 pi R sqrt(C1 C2)).
        # The resonance boosts the fundamental against the harmonics,
        # f0 slightly below the tone keeps the fundamental gain near unity.
        cutoff_ratio = 0.65  # f0 relative to the tone frequency
        c1 = 100e-9  # Feedback capacitor
        c2 = 10e-9  # Capacitor to ground
        resistances = _round_to_e_series(
            1 / (2 * numpy.pi * cutoff_ratio * self._frequencies * numpy.sqrt(c1 * c2)),
            _e_series(96),
        )

        # H(s) = 1 / (R1 R2 C1 C2 s^2 + C2 (R1 + R2) s + 1)
        coefficients = [
            scipy.signal.bilinear(
                [1.0],
                [r * r * c1 * c2, 2 * r * c2, 1.0],
                self._sample_rate,
            )
            for r in resistances
        ]
        # Filters start settled at the DC level of the square waves, as they run continuously
        states = [scipy.signal.lfilter_zi(b, a) * 0.5 for b, a in coefficients]

        for block in self._square_waves():
            filtered = numpy.empty(block.shape)
            for i, ((b, a), wave) in enumerate(zip(coefficients, block)):
                filtered[i], states[i] = scipy.signal.lfilter(b, a, wave, zi=states[i])

            yield filtered

    def _busbars(self):
        """Simulates the busbars, each pressed key connects one tone per busbar
        (tone index = key index + key offset) into a summing amplifier.

        Pressed keys are read at the start of each block.
        Yields blocks of shape (len(self._busbar_offsets), self.batch_size)."""

        for filtered in self._filtered_tones():
            # How many times each tone is connected to each busbar
            routing = numpy.zeros((len(self._busbar_offsets), len(self._frequencies)))
            for key in self._pressed_keys.copy():
                for bus, offset in enumerate(self._busbar_offsets):
                    routing[bus, self._key_indices[key] + offset] += 1

            # Subtracting 0.5 stands in for the DC blocking capacitor
            yield routing @ (filtered - 0.5)

    @property
    def mixing(self):
        return self._mixing

    @mixing.setter
    def mixing(self, values):
        values = numpy.array(values, dtype=float)
        assert values.shape == (len(self._busbar_offsets),)
        self._mixing = values

    def run(self):
        """Yields blocks of output samples, shape (self.batch_size,).
        Reads pressed keys and mixing at the start of each block."""

        # Mixing changes are ramped linearly over a block to avoid zipper noise
        ramp = numpy.linspace(0, 1, self._batch_size, endpoint=False)
        mixing = self._mixing

        for block in self._busbars():
            new_mixing = self._mixing
            gains = mixing[:, numpy.newaxis] + (new_mixing - mixing)[:, numpy.newaxis] * ramp
            mixing = new_mixing

            # tanh is a soft limiter
            yield numpy.tanh(self._output_gain * (gains * block).sum(axis=0))


def _e_series(steps):
    """Mantissas of the E-series with given number of steps per decade.
    The formula matches E48 and up, E24 and below use historical values that differ."""
    decimals = 1 if steps <= 24 else 2
    return numpy.round(
        numpy.logspace(0, 1, num=steps, endpoint=False), decimals=decimals
    )


def _round_to_e_series(values, series):
    """Rounds each value to the nearest (in log scale) value from the E-series."""
    decades = numpy.floor(numpy.log10(values))
    mantissas = values / 10**decades
    candidates = numpy.append(series, 10.0)
    indices = numpy.argmin(
        numpy.abs(numpy.log(mantissas[:, numpy.newaxis]) - numpy.log(candidates)),
        axis=1,
    )
    return candidates[indices] * 10**decades
